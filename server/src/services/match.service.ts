import Match from "../models/Match";
import ApiError from "../utils/apiError";
import Users from "../models/Users";
import Tournaments from "../models/Tournaments";
import Teams from "../models/Teams";
import {
  MatchDTO,
  TournamentMatchDTO,
  UpdateMatchDTO,
} from "../types/match.types";
import { Types } from "mongoose";

export const createMatch = async (userId: string, data: MatchDTO) => {
  if (!Types.ObjectId.isValid(userId))
    throw new ApiError("Invalid user ID", 400);

  if (!Types.ObjectId.isValid(data.tournament))
    throw new ApiError("Invalid tournament ID", 400);

  if (!Types.ObjectId.isValid(data.teamA))
    throw new ApiError("Invalid team A ID", 400);

  if (!Types.ObjectId.isValid(data.teamB))
    throw new ApiError("Invalid team B ID", 400);

  // A team cannot play against itself
  if (data.teamA === data.teamB)
    throw new ApiError("A team cannot play against itself", 400);

  // check if user exists
  const user = await Users.findById(userId);

  if (!user) throw new ApiError("User not found", 404);

  // verify user role
  const isAdminOrOrganizer = user.role === "admin" || user.role === "organizer";

  if (!isAdminOrOrganizer) throw new ApiError("Forbidden", 403);

  // check if tournament exists
  const tournament = await Tournaments.findById(data.tournament);

  if (!tournament) throw new ApiError("Tournament not found", 404);

  // check if teams exist
  const [teamA, teamB] = await Promise.all([
    Teams.findById(data.teamA),
    Teams.findById(data.teamB),
  ]);

  if (!teamA) throw new ApiError("Team A not found", 404);

  if (!teamB) throw new ApiError("Team B not found", 404);

  // Check that both teams are registered for this tournament
  const registeredTeamIds = tournament.registeredTeams.map((team) =>
    team.toString(),
  );

  if (!registeredTeamIds.includes(data.teamA)) {
    throw new ApiError("Team A is not registered for this tournament", 400);
  }

  if (!registeredTeamIds.includes(data.teamB)) {
    throw new ApiError("Team B is not registered for this tournament", 400);
  }

  // check if match already exists
  const matchExists = await Match.findOne({
    tournament: data.tournament,
    round: data.round,
    matchNumber: data.matchNumber,
  });

  if (matchExists)
    throw new ApiError("Match already exists for this round", 409);

  // create match
  const match = await Match.create({
    tournament: new Types.ObjectId(data.tournament),
    teamA: new Types.ObjectId(data.teamA),
    teamB: new Types.ObjectId(data.teamB),
    scheduledDate: new Date(data.scheduledDate),
    round: data.round,
    matchNumber: data.matchNumber,
  });

  return match;
};

/**
 * Create multiple matches generated by the frontend.
 *
 * The frontend is responsible for generating the tournament bracket.
 * The backend is responsible for validating and persisting it.
 */
export const createTournamentMatches = async (
  userId: string,
  tournamentId: string,
  matches: TournamentMatchDTO[],
) => {
  if (!Types.ObjectId.isValid(userId))
    throw new ApiError("Invalid user ID", 400);

  if (!Types.ObjectId.isValid(tournamentId))
    throw new ApiError("Invalid tournament ID", 400);

  // check if user exists
  const user = await Users.findById(userId);

  if (!user) throw new ApiError("User not found", 404);

  // verify user role
  const isAdminOrOrganizer = user.role === "admin" || user.role === "organizer";

  if (!isAdminOrOrganizer) throw new ApiError("Forbidden", 403);

  // check if tournament exists
  const tournament = await Tournaments.findById(tournamentId);

  if (!tournament) throw new ApiError("Tournament not found", 404);

  if (!matches || matches.length === 0)
    throw new ApiError("At least one match is required", 400);

  // Match numbers must be unique within the same round
  const matchKeys = new Set<string>();

  for (const match of matches) {
    if (!Types.ObjectId.isValid(match.teamA))
      throw new ApiError("Invalid team A ID", 400);

    if (!Types.ObjectId.isValid(match.teamB))
      throw new ApiError("Invalid team B ID", 400);

    if (match.teamA === match.teamB)
      throw new ApiError("A team cannot play against itself", 400);

    const key = `${match.round}-${match.matchNumber}`;

    if (matchKeys.has(key)) {
      throw new ApiError(
        `Duplicate match number ${match.matchNumber} in ${match.round}`,
        409,
      );
    }

    matchKeys.add(key);
  }

  // Get all teams involved in the generated bracket
  const teamIds = [
    ...new Set(matches.flatMap((match) => [match.teamA, match.teamB])),
  ];

  const teams = await Teams.find({
    _id: {
      $in: teamIds,
    },
  });

  // Ensure every team exists
  if (teams.length !== teamIds.length) {
    throw new ApiError("One or more teams do not exist", 404);
  }

  // Check that all teams are registered for the tournament
  const registeredTeamIds = new Set(
    tournament.registeredTeams.map((team) => team.toString()),
  );

  for (const teamId of teamIds) {
    if (!registeredTeamIds.has(teamId)) {
      throw new ApiError(
        `Team ${teamId} is not registered for this tournament`,
        400,
      );
    }
  }

  /**
   * Prevent duplicate match records that already exist in the database.
   *
   * We check before insertMany so the frontend receives a useful
   * application-level error rather than only a MongoDB duplicate-key error.
   */
  const existingMatches = await Match.find({
    tournament: tournamentId,
    $or: matches.map((match) => ({
      round: match.round,
      matchNumber: match.matchNumber,
    })),
  }).select("round matchNumber");

  if (existingMatches.length > 0) {
    const existing = existingMatches[0];

    throw new ApiError(
      `Match ${existing!.matchNumber} in ${existing!.round} already exists`,
      409,
    );
  }

  const matchDocuments = matches.map((match) => ({
    tournament: new Types.ObjectId(tournamentId),
    teamA: new Types.ObjectId(match.teamA),
    teamB: new Types.ObjectId(match.teamB),
    scheduledDate: new Date(match.scheduledDate),
    round: match.round,
    matchNumber: match.matchNumber,
  }));

  try {
    const createdMatches = await Match.insertMany(matchDocuments, {
      ordered: true,
    });

    return createdMatches;
  } catch (error: any) {
    // MongoDB duplicate-key protection from the unique index
    if (error?.code === 11000) {
      throw new ApiError("One or more matches already exist", 409);
    }

    throw error;
  }
};

export const getAllMatches = async (
  tournament: string,
  page: number,
  limit: number,
  status: string,
  team: string,
  round: string,
) => {
  const filter: any = {};

  const skip = (page - 1) * limit;

  if (tournament) {
    if (!Types.ObjectId.isValid(tournament))
      throw new ApiError("Invalid tournament ID", 400);

    filter.tournament = tournament;
  }

  if (status) {
    filter.status = status;
  }

  if (team) {
    if (!Types.ObjectId.isValid(team))
      throw new ApiError("Invalid team ID", 400);

    filter.$or = [{ teamA: team }, { teamB: team }];
  }

  if (round) {
    filter.round = round;
  }

  const [matches, total] = await Promise.all([
    Match.find(filter)
      .skip(skip)
      .limit(limit)
      .sort({
        round: 1,
        matchNumber: 1,
      })
      .populate("tournament", "name game banner")
      .populate("teamA", "name logo")
      .populate("teamB", "name logo")
      .populate("winner", "name logo"),

    Match.countDocuments(filter),
  ]);

  return {
    matches,
    total,
  };
};

export const getMatchById = async (matchId: string) => {
  if (!Types.ObjectId.isValid(matchId))
    throw new ApiError("Invalid match ID", 400);

  const match = await Match.findById(matchId)
    .populate("tournament", "name game banner")
    .populate("teamA", "name logo")
    .populate("teamB", "name logo")
    .populate("winner", "name logo");

  if (!match) throw new ApiError("Match not found", 404);

  return match;
};

export const updateMatch = async (
  userId: string,
  matchId: string,
  update: UpdateMatchDTO,
) => {
  if (!Types.ObjectId.isValid(userId))
    throw new ApiError("Invalid user ID", 400);

  if (!Types.ObjectId.isValid(matchId))
    throw new ApiError("Invalid match ID", 400);

  // check if user and match exist
  const user = await Users.findById(userId);

  if (!user) throw new ApiError("User not found", 404);

  const matchExists = await Match.findById(matchId);

  if (!matchExists) throw new ApiError("Match not found", 404);

  // verify user role
  const isAdminOrOrganizer = user.role === "admin" || user.role === "organizer";

  if (!isAdminOrOrganizer) throw new ApiError("Forbidden", 403);

  // If a winner is supplied, make sure the winner is one of the two teams
  if (update.winner) {
    if (!Types.ObjectId.isValid(update.winner))
      throw new ApiError("Invalid winner ID", 400);

    const isParticipant =
      matchExists.teamA.toString() === update.winner ||
      matchExists.teamB.toString() === update.winner;

    if (!isParticipant) {
      throw new ApiError(
        "Winner must be one of the teams participating in the match",
        400,
      );
    }
  }

  // update match
  const updatedMatch = await Match.findByIdAndUpdate(matchId, update, {
    new: true,
    runValidators: true,
  })
    .populate("tournament", "name game banner")
    .populate("teamA", "name logo")
    .populate("teamB", "name logo")
    .populate("winner", "name logo");

  return updatedMatch;
};

export const deleteMatch = async (userId: string, matchId: string) => {
  if (!Types.ObjectId.isValid(userId))
    throw new ApiError("Invalid user ID", 400);

  if (!Types.ObjectId.isValid(matchId))
    throw new ApiError("Invalid match ID", 400);

  // check if user and match exist
  const user = await Users.findById(userId);

  if (!user) throw new ApiError("User not found", 404);

  const matchExists = await Match.findById(matchId);

  if (!matchExists) throw new ApiError("Match not found", 404);

  // verify user role
  const isAdminOrOrganizer = user.role === "admin" || user.role === "organizer";

  if (!isAdminOrOrganizer) throw new ApiError("Forbidden", 403);

  // delete match
  await Match.findByIdAndDelete(matchId);

  return null;
};
