import { Request, Response } from "express";
import asyncHandler from "../utils/asyncHandler";
import * as tournamentService from "../services/tournament.service";
import ApiError from "../utils/apiError";
import * as matchService from "../services/match.service";

/**
 * Create Tournament
 */
export const createTournament = asyncHandler(
  async (req: Request, res: Response) => {
    const userId = req.user?.userId as string;

    const tournament = await tournamentService.createNewTournament(
      userId,
      req.body,
    );

    res.status(201).json({
      success: true,
      message: "Tournament created successfully",
      data: tournament,
    });
  },
);

// Creates multiple matches generated by the frontend.
export const createTournamentMatches = asyncHandler(
  async (req: Request, res: Response) => {
    const userId = req.user?.userId as string;

    const tournamentId = req.params.tournamentId as string;

    const { matches } = req.body;

    const createdMatches = await matchService.createTournamentMatches(
      userId,
      tournamentId,
      matches,
    );

    res.status(201).json({
      success: true,
      message: "Tournament matches created successfully",
      data: createdMatches,
    });
  },
);

// Get All Tournaments

export const findAllTournaments = asyncHandler(
  async (req: Request, res: Response) => {
    const search = String(req.query.search ?? "");
    const game = String(req.query.game ?? "");
    const region = String(req.query.region ?? "");
    const status = String(req.query.status ?? "");

    const page = Math.max(Number(req.query.page) || 1, 1);

    const limit = Math.min(Math.max(Number(req.query.limit) || 10, 1), 50);

    const tournaments = await tournamentService.getAllTournaments(
      search,
      game,
      page,
      limit,
      region,
      status,
    );

    res.status(200).json({
      success: true,
      message: "Tournaments retrieved successfully",
      data: tournaments.allTournaments,
      pagination: {
        page,
        limit,
        total: tournaments.total,
        totalPages: Math.ceil(tournaments.total / limit),
      },
    });
  },
);

